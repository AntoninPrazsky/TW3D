namespace TW3D.Editor
{
    /// <summary>
    /// The level editor: the level being edited (an <see cref="EditedLevel"/>, the document with undo) drawn as in the
    /// game, seen by a free camera (<see cref="EditorCamera"/>), edited with the <see cref="BlockTool"/> whose cursor
    /// the <see cref="EditorMarkers"/> show, with the user interface of Dear ImGui over it (the menu bar, the status bar
    /// and the windows: the <see cref="PaletteWindow"/> with the <see cref="BlockPreviews"/>, the help, the
    /// <see cref="FileDialogs"/>). Levels are opened from and saved into the <see cref="LevelFolder"/>; what would drop
    /// unsaved changes (a new level, opening another, leaving, closing the window) waits as a <see cref="PendingAction"/>
    /// for the answer to "Save changes?"; the recent levels and the last level with its camera are kept in the
    /// <see cref="EditorSettings"/>. Opened by <c>--editor [level]</c>, alone on the screen stack (leaving it quits), or
    /// from the main menu of a Debug build (leaving it goes back to the menu). The scene gets the mouse and the keys only
    /// when the interface does not want them (the cursor over a window, a text field being typed in) and no dialog is open.
    /// </summary>
    public sealed class EditorScreen : Screen
    {
        //The font of the interface (DejaVu Sans, approved by the FSF; its licence is content/Fonts/DejaVuSans-LICENSE.txt) and its size in pixels
        //on a 1920 × 1080 window, scaled with the window
        private const string FontFile = "Fonts/DejaVuSans.ttf";
        private const float FontSize = 17f;
        //Where ImGui keeps the positions and sizes of its windows
        private static readonly string LayoutFile = Path.Combine(
            Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), "TW3D", "editor-layout.ini");
        //Where the sky is drawn relative to the camera: around it, as the game draws it around the car
        private static readonly Vector3 SkyOffset = new Vector3(0f, -2f, 6.5f);
        //How far the camera of the game is from the car (scene units): the haze of the renderer is set for that distance,
        //so it is moved by what the camera of the editor is further
        private const float GameCameraDistance = 4.5f;
        //How far from the camera the shadows reach, at least (see SceneRenderer.ShadowDistance)
        private const float MinShadowDistance = 40f;
        private const string TitlePrefix = "Level Editor - ";
        private static readonly System.Numerics.Vector4 WarningColor = new System.Numerics.Vector4(1f, 0.8f, 0.3f, 1f);

        private readonly GameSettings settings;
        private readonly string levelArgument;
        private readonly string levelsArgument;
        //Opened from the command line, alone: leaving quits the game; otherwise leaving goes back to the menu
        private readonly bool standalone;
        //The title of the window before the editor, put back when it leaves
        private string previousTitle;

        private LevelAssets assets;
        private SceneRenderer renderer;
        private Model sky;
        private EditorCamera camera;
        private LevelView view;
        private EditedLevel level;
        private BlockTool tool;
        private EditorMarkers markers;
        private ImGuiRenderer imgui;
        private BlockPreviews previews;
        private PaletteWindow palette;
        private LevelFolder folder;
        private EditorSettings editorSettings;
        private FileDialogs dialogs;
        private readonly PendingAction pending = new PendingAction();
        private ImGuiStyle defaultStyle;
        private int fontSize;
        //The size of a preview of the palette in pixels, scaled with the window
        private int previewSize;
        private bool showPalette = true, showHelp, showDemo;
        private Layer layer = Layer.Middle;
        //The title of the window says the level has unsaved changes; the title is set again when that changes
        private bool titleDirty;
        //What the status bar says about the last thing done
        private string message = "";
        //What the status bar keeps saying about the level opened (a level generated by a script); null for nothing
        private string warning;
        //The window had no focus: the click that brings it back is not an edit
        private bool focusReturning;
        //The editor is leaving (nothing unsaved, or the user let the changes go): the exit of the game it causes is let through
        private bool leaving;
        //A dialog was open in the last frame: the keys held when it closed answered it (D of Don't save would fly the
        //camera), so the scene gets no keys until they are released
        private bool dialogWasOpen;
        private Keys[] dialogKeys = Array.Empty<Keys>();

        /// <param name="level">A level name (a file of the levels folder without the extension) or a level file; null = the last level, or a new one.</param>
        /// <param name="standalone">The editor is alone (opened by --editor): leaving it quits the game instead of going back to the menu.</param>
        /// <param name="levels">The levels folder given by --levels; null = the repository's content/Levels or the application data (see <see cref="LevelFolder"/>).</param>
        public EditorScreen(GameSettings settings, string level, bool standalone, string levels = null)
        {
            this.settings = settings;
            levelArgument = level;
            levelsArgument = levels;
            this.standalone = standalone;
            FadeInTime = TimeSpan.Zero;
            FadeOutTime = TimeSpan.Zero;
            IsOpaque = true;
        }

        private string LevelName => level.File != null ? Path.GetFileNameWithoutExtension(level.File) : "new level";

        //"Save changes to lock?", but "Save changes to the new level?"
        private string PromptName => level.File != null ? LevelName : "the new level";

        public override unsafe void LoadContent()
        {
            ShowImmediately();
            Manager.PointersVisible = false;
            previousTitle = Manager.Game.Window.Title;

            assets = LevelAssets.Load(Manager.Content);
            renderer = new SceneRenderer(Manager.GraphicsDevice, Manager.Content);
            settings.Apply(renderer);
            sky = Manager.Content.Load<Model>("Env/sky");
            camera = new EditorCamera();
            view = new LevelView(assets);
            tool = new BlockTool(camera, note => message = note);
            markers = new EditorMarkers(Manager.GraphicsDevice, Manager.Content);

            imgui = new ImGuiRenderer(Manager.Game, LayoutFile);
            ImGui.GetIO().ConfigFlags |= ImGuiConfigFlags.DockingEnable;
            defaultStyle = *ImGui.GetStyle().NativePtr;
            previews = new BlockPreviews(Manager.GraphicsDevice, assets, imgui);
            palette = new PaletteWindow(previews, assets.Catalog);

            folder = LevelFolder.Find(levelsArgument);
            editorSettings = EditorSettings.Load(EditorSettings.DefaultPath);
            dialogs = new FileDialogs(Manager.GraphicsDevice, imgui, folder, file => Guard(() => OpenLevel(file)), SaveAsTo,
                () => pending.SaveAsFinished(false), Answer);
            //The close button of the window asks too when there are unsaved changes
            Manager.Game.Exiting += OnExiting;

            OpenFirst();
        }

        public override void UnloadContent()
        {
            Manager.Game.Exiting -= OnExiting;
            tool.EndStroke();
            dialogs.Dispose();
            previews.Dispose();
            imgui.Dispose();
            Manager.PointersVisible = true;
            Manager.Game.Window.Title = previousTitle;
        }

        /// <summary>The level the editor starts with: the one asked for, else the last one edited while its file exists, else a new one.</summary>
        private void OpenFirst()
        {
            if (levelArgument != null)
            {
                string file = folder.Resolve(levelArgument);
                if (File.Exists(file))
                    OpenLevel(file);
                else
                {
                    NewLevel();
                    message = "Level " + levelArgument + " was not found in " + folder.FullPath + "; a new level.";
                }
            }
            else if (editorSettings.LastLevel != null && File.Exists(editorSettings.LastLevel))
                OpenLevel(editorSettings.LastLevel);
            else
                NewLevel();
        }

        /// <summary>
        /// Opens a level file; a file that cannot be read leaves the level being edited as it is (a new level when there
        /// is none yet). The last level edited gets its camera back; another level is framed.
        /// </summary>
        private void OpenLevel(string file)
        {
            string fullPath = Path.GetFullPath(file);
            EditedLevel opened;
            try
            {
                opened = new EditedLevel(assets.Catalog, LevelFile.Load(fullPath), fullPath);
            }
            catch (Exception e) when (e is IOException || e is UnauthorizedAccessException || e is InvalidDataException
                || e is System.Text.Json.JsonException)
            {
                if (level == null)
                    NewLevel();
                message = "Could not read " + fullPath + ": " + e.Message;
                return;
            }

            RememberLevel();
            bool last = editorSettings.LastLevel != null && LevelFolder.SamePath(editorSettings.LastLevel, fullPath);
            CameraView saved = last ? editorSettings.Camera : null;
            editorSettings.AddRecent(fullPath);
            editorSettings.LastLevel = fullPath;
            if (!last)
                editorSettings.Camera = null;
            editorSettings.Save(EditorSettings.DefaultPath);

            Show(opened, saved);
            List<LevelProblem> problems = level.Problems();
            message = problems.Count == 0 ? "Opened " + Path.GetFileName(fullPath) + "."
                : Count(problems.Count, "problem") + " in the level: " + problems[0];
        }

        /// <summary>A new level with the start block only.</summary>
        private void NewLevel()
        {
            RememberLevel();
            Show(EditedLevel.New(assets.Catalog), null);
            message = "A new level.";
        }

        /// <summary>A level becomes the one edited: the view, the tool, the title and the camera (where it was, or framing the level).</summary>
        private void Show(EditedLevel opened, CameraView saved)
        {
            level = opened;
            view.Level = level;
            tool.Level = level;
            SetTitle();
            UpdateWarning();
            if (saved != null)
            {
                camera.Target = new Vector3(saved.TargetX, saved.TargetY, saved.TargetZ);
                camera.Yaw = saved.Yaw;
                camera.Pitch = saved.Pitch;
                camera.Distance = saved.Distance;
            }
            else
                FrameLevel();
        }

        /// <summary>The level being edited (when it has a file) is the last level, with the camera where it is now.</summary>
        private void RememberLevel()
        {
            if (level == null || level.File == null)
                return;
            editorSettings.LastLevel = level.File;
            editorSettings.Camera = new CameraView
            {
                TargetX = camera.Target.X,
                TargetY = camera.Target.Y,
                TargetZ = camera.Target.Z,
                Yaw = camera.Yaw,
                Pitch = camera.Pitch,
                Distance = camera.Distance
            };
            editorSettings.Save(EditorSettings.DefaultPath);
        }

        /// <summary>A level of the repository that a script of tools/levelgen generates: changes made here are lost when it runs again.</summary>
        private void UpdateWarning()
        {
            string script = folder.GeneratorOf(level.File);
            warning = script != null
                ? "This level is generated by " + script + ": running the script again overwrites changes made here."
                : null;
        }

        /// <summary>
        /// Saves the level into its file. A new level and a level read from an old .lev file (which is never overwritten)
        /// need a name: Save as asks for it.
        /// </summary>
        private SaveOutcome Save()
        {
            if (level.File == null || level.File.EndsWith(LevelFile.LegacyExtension, StringComparison.OrdinalIgnoreCase))
            {
                SaveAs();
                return SaveOutcome.SavingAs;
            }
            return Write(level.File, false) ? SaveOutcome.Saved : SaveOutcome.Failed;
        }

        /// <summary>Asks for a name in the levels folder to save the level as, offering its own.</summary>
        private void SaveAs()
        {
            tool.EndStroke();
            dialogs.ShowSaveAs(level.File != null ? Path.GetFileNameWithoutExtension(level.File) : "");
        }

        /// <summary>Save as chose a file (confirmed when it existed): the level is saved as it, and an action waiting for the save goes on.</summary>
        private void SaveAsTo(string file)
        {
            pending.SaveAsFinished(Write(file, true));
        }

        /// <summary>
        /// Writes the level into a file and tells how it went in the status bar; a level of the repository is copied to the
        /// build output too, for the game. A failure leaves the level with its changes.
        /// </summary>
        /// <param name="saveAs">The file becomes the level's file.</param>
        private bool Write(string file, bool saveAs)
        {
            //A stroke still being painted (Ctrl+S with the button held) is closed first: otherwise the file would have
            //its cells while the saved point of undo is before it, and undoing it would look clean with the file changed
            tool.EndStroke();
            string fileName = Path.GetFileName(file);
            try
            {
                Directory.CreateDirectory(Path.GetDirectoryName(file));
                LevelFile.Save(level.ToData(), file);
            }
            catch (Exception e) when (e is IOException || e is UnauthorizedAccessException)
            {
                message = "Could not save " + fileName + ": " + e.Message;
                return false;
            }

            if (saveAs)
                level.SavedAs(file);
            else
                level.MarkSaved();
            List<LevelProblem> problems = level.Problems();
            message = problems.Count == 0 ? "Saved " + fileName + "."
                : "Saved " + fileName + "; " + Count(problems.Count, "problem") + ": " + problems[0];
            try
            {
                folder.CopyToBuild(file);
            }
            catch (Exception e) when (e is IOException || e is UnauthorizedAccessException)
            {
                message += " Not copied to the build output: " + e.Message;
            }

            editorSettings.AddRecent(file);
            if (editorSettings.LastLevel == null || !LevelFolder.SamePath(editorSettings.LastLevel, file))
            {
                editorSettings.LastLevel = file;
                editorSettings.Camera = null;
            }
            editorSettings.Save(EditorSettings.DefaultPath);
            SetTitle();
            UpdateWarning();
            return true;
        }

        private static string Count(int count, string noun) => count + " " + noun + (count == 1 ? "" : "s");

        /// <summary>Runs an action that would drop the unsaved changes of the level, asking "Save changes?" first when there are some.</summary>
        private void Guard(Action action)
        {
            tool.EndStroke();
            pending.Request(level.IsDirty, action);
            if (pending.IsAsking)
                dialogs.AskSaveChanges(PromptName);
        }

        /// <summary>The answer to "Save changes?": the waiting action runs after the save (once Save as named the level), at once, or not at all.</summary>
        private void Answer(SaveChangesAnswer answer)
        {
            switch (answer)
            {
                case SaveChangesAnswer.Save:
                    pending.Saved(Save());
                    break;
                case SaveChangesAnswer.DontSave:
                    pending.DontSave();
                    break;
                default:
                    pending.Cancel();
                    break;
            }
        }

        /// <summary>
        /// The game is closing (the close button of the window, or the editor's own exit): the editor's own exit and an
        /// exit without unsaved changes go through; otherwise the game stays and asks, and quits by the answer.
        /// </summary>
        private void OnExiting(object sender, ExitingEventArgs e)
        {
            if (leaving)
                return;
            if (!level.IsDirty)
            {
                RememberLevel();
                leaving = true;
                return;
            }
            e.Cancel = true;
            pending.Cancel();
            Guard(Quit);
        }

        /// <summary>Quits the game, whatever opened the editor (the close button of the window).</summary>
        private void Quit()
        {
            RememberLevel();
            leaving = true;
            Manager.Game.Exit();
        }

        /// <summary>The title of the window: the name of the level, with a star while it has unsaved changes.</summary>
        private void SetTitle()
        {
            titleDirty = level.IsDirty;
            Manager.Game.Window.Title = TitlePrefix + LevelName + (titleDirty ? "*" : "");
        }

        /// <summary>The camera sees the whole level.</summary>
        private void FrameLevel()
        {
            BoundingBox? bounds = view.SceneBounds();
            if (bounds.HasValue)
                camera.Frame(bounds.Value, Manager.Viewport.AspectRatio);
            else
                camera.Reset();
        }

        /// <summary>Leaves the editor: quits the game when the editor is alone, otherwise goes back to the menu.</summary>
        private void Leave()
        {
            RememberLevel();
            leaving = true;
            if (standalone)
                Manager.Game.Exit();
            else
                Close();
        }

        private void CycleMood()
        {
            level.SetMood((LevelMood)(((int)level.Mood + 1) % 3));
        }

        public override void Update(GameTime gameTime)
        {
            //Without the focus the screen gets no input, so it would not see the button go up: a stroke ends here
            if (!HasFocus)
            {
                tool.EndStroke();
                focusReturning = true;
            }
            if (level.IsDirty != titleDirty)
                SetTitle();
        }

        public override void HandleInput(InputState input, GameTime gameTime)
        {
            //A dialog has the keys and the mouse; the key that closes it is not seen again here, as it was pressed before
            if (dialogs.IsOpen)
            {
                tool.EndStroke();
                dialogWasOpen = true;
                return;
            }
            if (dialogWasOpen)
            {
                dialogWasOpen = false;
                dialogKeys = input.Keyboard.GetPressedKeys();
            }
            bool dialogKeysHeld = Array.Exists(dialogKeys, key => input.IsKeyDown(key));
            if (!dialogKeysHeld)
                dialogKeys = Array.Empty<Keys>();

            float elapsed = (float)gameTime.ElapsedGameTime.TotalSeconds;
            ImGuiIOPtr io = ImGui.GetIO();
            bool keysFree = !io.WantCaptureKeyboard && !dialogKeysHeld;
            bool mouseFree = !io.WantCaptureMouse;
            bool control = input.IsKeyDown(Keys.LeftControl) || input.IsKeyDown(Keys.RightControl);
            bool shift = input.IsKeyDown(Keys.LeftShift) || input.IsKeyDown(Keys.RightShift);

            //The shortcuts of the menus work while a text field of a window has the keyboard too
            if (control && !dialogKeysHeld)
                HandleShortcuts(input, shift);

            if (keysFree && !dialogs.IsOpen)
            {
                if (input.KeyPressed(Keys.Escape))
                    Guard(Leave);
                if (input.KeyPressed(Keys.F1))
                    showHelp = !showHelp;
                if (input.KeyPressed(Keys.F9))
                    renderer.Classic = !renderer.Classic;
                if (input.KeyPressed(Keys.F10))
                    renderer.Shadows = !renderer.Shadows;
                if (input.KeyPressed(Keys.F11))
                    renderer.AmbientOcclusion = !renderer.AmbientOcclusion;
                if (input.KeyPressed(Keys.M))
                    CycleMood();
                if (input.KeyPressed(Keys.Home))
                    FrameLevel();
                //The layer being edited: Tab cycles, Right Shift and Right Ctrl toggle as in the old editor
                if (input.KeyPressed(Keys.Tab))
                    layer = (Layer)(((int)layer + 1) % 3);
                if (input.KeyPressed(Keys.RightShift))
                    layer = layer == Layer.Back ? Layer.Middle : Layer.Back;
                if (input.KeyPressed(Keys.RightControl))
                    layer = layer == Layer.Front ? Layer.Middle : Layer.Front;
                camera.HandleKeys(input, elapsed);
                tool.HandleKeys(input, layer);
            }
            if (dialogs.IsOpen)
                return;

            //The camera has the mouse first: its drags take precedence over the tool, and Ctrl + the wheel is the tool's
            Viewport viewport = Manager.Viewport;
            camera.HandleMouse(input, viewport, mouseFree, !control);
            tool.HandleMouse(input, viewport, layer, mouseFree && !focusReturning);
            focusReturning = false;
        }

        /// <summary>Ctrl+N, Ctrl+O, Ctrl+S, Ctrl+Shift+S of the File menu and Ctrl+Z, Ctrl+Y (Ctrl+Shift+Z) of the Edit menu.</summary>
        private void HandleShortcuts(InputState input, bool shift)
        {
            if (input.KeyPressed(Keys.N))
                Guard(NewLevel);
            else if (input.KeyPressed(Keys.O))
                ShowOpen();
            else if (input.KeyPressed(Keys.S))
            {
                if (shift)
                    SaveAs();
                else
                    Save();
            }
            //Ctrl+Shift+Z redoes as in the editors of today, Ctrl+Y as in Windows
            else if (input.KeyPressed(Keys.Z) && !shift)
                tool.Undo();
            else if (input.KeyPressed(Keys.Y) || input.KeyPressed(Keys.Z) && shift)
                tool.Redo();
        }

        private void ShowOpen()
        {
            tool.EndStroke();
            dialogs.ShowOpen(level.File);
        }

        public override void Draw(GameTime gameTime)
        {
            //The previews of the palette are drawn first: switching render targets may discard the screen, and the
            //scene, drawn after them, covers it anyway
            previewSize = Math.Max(16, (int)Math.Round(BlockPreviews.ReferenceCellSize * Manager.UiScale));
            if (showPalette && palette.NeedsPreviews)
                previews.Draw(previewSize, (float)gameTime.ElapsedGameTime.TotalSeconds);

            Viewport viewport = Manager.Viewport;
            camera.Update(viewport);

            renderer.Lighting = Lighting.For(level.Mood);
            renderer.HazeOffset = Math.Max(0f, camera.Distance - GameCameraDistance);
            renderer.ShadowDistance = Math.Max(MinShadowDistance, camera.Distance * 1.5f);
            renderer.Begin(camera.View, camera.Projection);
            renderer.SetBackground(sky, Matrix.CreateScale(Units.ModelToScene) * Matrix.CreateTranslation(camera.Position + SkyOffset));
            view.Draw(renderer);
            renderer.End();
            markers.Draw(camera.View, camera.Projection, layer, tool.Cursor, level.Finish);

            UpdateFont();
            imgui.BeforeLayout(gameTime);
            DrawInterface();
            imgui.AfterLayout();
        }

        /// <summary>The font and the sizes of the interface follow the size of the window.</summary>
        private unsafe void UpdateFont()
        {
            int size = Math.Max(8, (int)Math.Round(FontSize * Manager.UiScale));
            if (size == fontSize)
                return;
            fontSize = size;
            imgui.LoadFont(Path.Combine(AppContext.BaseDirectory, Manager.Content.RootDirectory, FontFile), size);

            ImGuiStylePtr style = ImGui.GetStyle();
            *style.NativePtr = defaultStyle;
            ImGui.StyleColorsDark();
            style.WindowRounding = 4f;
            style.FrameRounding = 3f;
            style.ScaleAllSizes(size / FontSize);
        }

        private void DrawInterface()
        {
            ImGuiViewportPtr viewport = ImGui.GetMainViewport();
            float statusHeight = ImGui.GetFrameHeightWithSpacing();

            DrawMenuBar();
            DrawDockSpace(viewport, statusHeight);
            DrawStatusBar(viewport, statusHeight);
            if (showPalette)
                DrawPalette(viewport);
            if (showHelp)
                DrawHelp();
            if (showDemo)
                ImGui.ShowDemoWindow(ref showDemo);
            //At the root of the ID stack, where the popups of the dialogs are opened, whatever asked for them (a menu, a key)
            dialogs.Draw(ImGui.GetFontSize() / FontSize);
        }

        private void DrawMenuBar()
        {
            if (!ImGui.BeginMainMenuBar())
                return;

            if (ImGui.BeginMenu("File"))
            {
                if (ImGui.MenuItem("New", "Ctrl+N"))
                    Guard(NewLevel);
                if (ImGui.MenuItem("Open...", "Ctrl+O"))
                    ShowOpen();
                if (ImGui.BeginMenu("Open recent"))
                {
                    DrawRecent();
                    ImGui.EndMenu();
                }
                ImGui.Separator();
                if (ImGui.MenuItem("Save", "Ctrl+S"))
                    Save();
                if (ImGui.MenuItem("Save as...", "Ctrl+Shift+S"))
                    SaveAs();
                ImGui.Separator();
                if (ImGui.MenuItem(standalone ? "Exit" : "Back to the menu", "Esc"))
                    Guard(Leave);
                ImGui.EndMenu();
            }
            if (ImGui.BeginMenu("Edit"))
            {
                if (ImGui.MenuItem(level.CanUndo ? "Undo " + level.UndoName : "Undo", "Ctrl+Z", false, level.CanUndo))
                    tool.Undo();
                if (ImGui.MenuItem(level.CanRedo ? "Redo " + level.RedoName : "Redo", "Ctrl+Y", false, level.CanRedo))
                    tool.Redo();
                ImGui.EndMenu();
            }
            if (ImGui.BeginMenu("View"))
            {
                if (ImGui.MenuItem("Lighting of 2016", "F9", renderer.Classic))
                    renderer.Classic = !renderer.Classic;
                if (ImGui.MenuItem("Shadows", "F10", renderer.Shadows))
                    renderer.Shadows = !renderer.Shadows;
                if (ImGui.MenuItem("Ambient occlusion", "F11", renderer.AmbientOcclusion))
                    renderer.AmbientOcclusion = !renderer.AmbientOcclusion;
                ImGui.Separator();
                if (ImGui.BeginMenu("Layer"))
                {
                    foreach (Layer candidate in Enum.GetValues<Layer>())
                        if (ImGui.MenuItem(candidate.ToString(), null, layer == candidate))
                            layer = candidate;
                    ImGui.EndMenu();
                }
                if (ImGui.MenuItem("Frame the level", "Home"))
                    FrameLevel();
                ImGui.Separator();
                ImGui.MenuItem("Palette", null, ref showPalette);
                ImGui.MenuItem("ImGui demo window", null, ref showDemo);
                ImGui.EndMenu();
            }
            if (ImGui.BeginMenu("Level"))
            {
                if (ImGui.BeginMenu("Mood"))
                {
                    foreach (LevelMood mood in Enum.GetValues<LevelMood>())
                        if (ImGui.MenuItem(mood.ToString(), mood == LevelMood.Day ? "M" : null, level.Mood == mood))
                            level.SetMood(mood);
                    ImGui.EndMenu();
                }
                ImGui.EndMenu();
            }
            if (ImGui.BeginMenu("Help"))
            {
                ImGui.MenuItem("Controls", "F1", ref showHelp);
                ImGui.EndMenu();
            }
            ImGui.EndMainMenuBar();
        }

        /// <summary>The items of File > Open recent: the levels opened or saved last whose files still exist, the folder as a tooltip.</summary>
        private void DrawRecent()
        {
            bool any = false;
            //A copy: opening a level reorders the list
            foreach (string file in new List<string>(editorSettings.Recent))
            {
                if (!File.Exists(file))
                    continue;
                any = true;
                string label = file.EndsWith(LevelFile.Extension, StringComparison.OrdinalIgnoreCase)
                    ? Path.GetFileNameWithoutExtension(file) : Path.GetFileName(file);
                if (ImGui.MenuItem(label + "##" + file))
                    Guard(() => OpenLevel(file));
                ImGui.SetItemTooltip(Path.GetDirectoryName(file));
            }
            if (!any)
                ImGui.TextDisabled("No recent levels");
        }

        /// <summary>
        /// A dock space over the whole work area between the menu bar and the status bar: the windows can be docked to its
        /// edges, and the scene shows through its middle, where the mouse is the scene's.
        /// </summary>
        private static void DrawDockSpace(ImGuiViewportPtr viewport, float statusHeight)
        {
            ImGui.SetNextWindowPos(viewport.WorkPos);
            ImGui.SetNextWindowSize(new System.Numerics.Vector2(viewport.WorkSize.X, viewport.WorkSize.Y - statusHeight));
            ImGui.SetNextWindowViewport(viewport.ID);
            ImGui.PushStyleVar(ImGuiStyleVar.WindowRounding, 0f);
            ImGui.PushStyleVar(ImGuiStyleVar.WindowBorderSize, 0f);
            ImGui.PushStyleVar(ImGuiStyleVar.WindowPadding, System.Numerics.Vector2.Zero);
            const ImGuiWindowFlags flags = ImGuiWindowFlags.NoDocking | ImGuiWindowFlags.NoTitleBar | ImGuiWindowFlags.NoCollapse
                | ImGuiWindowFlags.NoResize | ImGuiWindowFlags.NoMove | ImGuiWindowFlags.NoBringToFrontOnFocus | ImGuiWindowFlags.NoNavFocus
                | ImGuiWindowFlags.NoBackground | ImGuiWindowFlags.NoSavedSettings;
            ImGui.Begin("Editor dock space", flags);
            ImGui.PopStyleVar(3);
            ImGui.DockSpace(ImGui.GetID("EditorDockSpace"), System.Numerics.Vector2.Zero, ImGuiDockNodeFlags.PassthruCentralNode);
            ImGui.End();
        }

        private void DrawStatusBar(ImGuiViewportPtr viewport, float height)
        {
            ImGui.SetNextWindowPos(new System.Numerics.Vector2(viewport.WorkPos.X, viewport.WorkPos.Y + viewport.WorkSize.Y - height));
            ImGui.SetNextWindowSize(new System.Numerics.Vector2(viewport.WorkSize.X, height));
            ImGui.PushStyleVar(ImGuiStyleVar.WindowRounding, 0f);
            ImGui.PushStyleVar(ImGuiStyleVar.WindowBorderSize, 0f);
            const ImGuiWindowFlags flags = ImGuiWindowFlags.NoDecoration | ImGuiWindowFlags.NoMove | ImGuiWindowFlags.NoSavedSettings
                | ImGuiWindowFlags.NoDocking | ImGuiWindowFlags.NoBringToFrontOnFocus | ImGuiWindowFlags.NoNavFocus;
            ImGui.Begin("Status bar", flags);
            ImGui.PopStyleVar(2);

            ImGui.Text($"Cell: {tool.Cursor.X}, {tool.Cursor.Y}");
            Separate();
            ImGui.Text("Layer: " + layer);
            Separate();
            ImGui.Text("Tool: Place");
            Separate();
            ImGui.Text($"Block: {tool.Block}, shift {tool.Shift}");
            if (palette.Object != null)
            {
                Separate();
                ImGui.Text($"Object: {palette.Object.Type} {palette.Object.Model}");
            }
            Separate();
            ImGui.Text((level.File != null ? Path.GetFileName(level.File) : LevelName) + (level.IsDirty ? "*" : ""));
            if (ImGui.IsItemHovered())
                ImGui.SetTooltip((level.File ?? "Not saved yet") + "\nLevels folder: " + folder.FullPath);
            if (warning != null)
            {
                Separate();
                ImGui.TextColored(WarningColor, warning);
            }
            if (message.Length > 0)
            {
                Separate();
                ImGui.TextDisabled(message);
            }
            ImGui.End();
        }

        /// <summary>A gap between the items of the status bar.</summary>
        private static void Separate()
        {
            ImGui.SameLine(0f, ImGui.GetFontSize());
            ImGui.TextDisabled("|");
            ImGui.SameLine(0f, ImGui.GetFontSize());
        }

        private void DrawPalette(ImGuiViewportPtr viewport)
        {
            palette.Draw(ref showPalette, viewport, tool, layer, previewSize, ImGui.GetFontSize() / FontSize);
        }

